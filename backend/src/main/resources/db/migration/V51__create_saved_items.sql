CREATE TABLE saved_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    post_id BIGINT REFERENCES community_posts(id) ON DELETE CASCADE,
    image_id BIGINT REFERENCES community_album_images(file_id) ON DELETE CASCADE,
    saved_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((post_id IS NOT NULL AND image_id IS NULL) OR (post_id IS NULL AND image_id IS NOT NULL)),
    UNIQUE (user_id, post_id),
    UNIQUE (user_id, image_id)
);

CREATE INDEX idx_saved_items_user ON saved_items (user_id, saved_at DESC);
CREATE INDEX idx_saved_items_post ON saved_items (post_id);
CREATE INDEX idx_saved_items_image ON saved_items (image_id);
