CREATE TABLE community_albums (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id BIGINT NOT NULL REFERENCES communities(id) ON DELETE CASCADE,
    title VARCHAR(120) NOT NULL,
    description VARCHAR(500) NOT NULL
);

CREATE INDEX idx_community_albums_group ON community_albums (community_id, id);

CREATE TABLE community_album_images (
    album_id BIGINT NOT NULL REFERENCES community_albums(id) ON DELETE CASCADE,
    file_id BIGINT NOT NULL UNIQUE REFERENCES stored_files(id) ON DELETE CASCADE,
    PRIMARY KEY (album_id, file_id)
);