ALTER TABLE community_tasks ADD CONSTRAINT uq_community_tasks_group_id UNIQUE (community_id, id);

CREATE TABLE community_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id BIGINT NOT NULL REFERENCES communities(id) ON DELETE CASCADE,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    due_date DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (community_id, id)
);

CREATE INDEX idx_community_goals_group ON community_goals (community_id, id);

CREATE TABLE community_goal_tasks (
    community_id BIGINT NOT NULL,
    goal_id BIGINT NOT NULL,
    task_id BIGINT NOT NULL,
    PRIMARY KEY (goal_id, task_id),
    FOREIGN KEY (community_id, goal_id) REFERENCES community_goals(community_id, id) ON DELETE CASCADE,
    FOREIGN KEY (community_id, task_id) REFERENCES community_tasks(community_id, id) ON DELETE CASCADE
);

CREATE INDEX idx_community_goal_tasks_task ON community_goal_tasks (community_id, task_id);
