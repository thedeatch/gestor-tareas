CREATE TABLE community_image_share_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_id BIGINT NOT NULL REFERENCES community_album_images(file_id) ON DELETE CASCADE,
    created_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_gallery_image_share_creator UNIQUE (image_id, created_by_user_id)
);

CREATE INDEX idx_gallery_image_share_token
    ON community_image_share_links(token, revoked_at);
