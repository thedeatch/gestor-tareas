CREATE TABLE community_polls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id BIGINT NOT NULL REFERENCES communities(id) ON DELETE CASCADE,
    author_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    question VARCHAR(300) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closes_at TIMESTAMP WITH TIME ZONE,
    closed_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_community_polls_group ON community_polls (community_id, id);

CREATE TABLE community_poll_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poll_id BIGINT NOT NULL REFERENCES community_polls(id) ON DELETE CASCADE,
    label VARCHAR(200) NOT NULL,
    position INTEGER NOT NULL,
    UNIQUE (poll_id, position),
    UNIQUE (poll_id, id)
);

CREATE TABLE community_poll_votes (
    poll_id BIGINT NOT NULL REFERENCES community_polls(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    option_id BIGINT NOT NULL,
    PRIMARY KEY (poll_id, user_id),
    FOREIGN KEY (poll_id, option_id) REFERENCES community_poll_options(poll_id, id) ON DELETE CASCADE
);

CREATE INDEX idx_community_poll_votes_option ON community_poll_votes (poll_id, option_id);
