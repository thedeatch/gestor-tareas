CREATE TABLE private_chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    recipient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    content VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (sender_id <> recipient_id)
);
CREATE INDEX idx_private_chat_sender ON private_chat_messages (sender_id, recipient_id, id DESC);
CREATE INDEX idx_private_chat_recipient ON private_chat_messages (recipient_id, sender_id, id DESC);