CREATE TABLE community_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id BIGINT NOT NULL REFERENCES communities(id) ON DELETE CASCADE,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    title VARCHAR(120) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    starts_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_community_events_schedule ON community_events (community_id, starts_at, id);

CREATE TABLE community_event_registrations (
    event_id BIGINT NOT NULL REFERENCES community_events(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (event_id, user_id)
);