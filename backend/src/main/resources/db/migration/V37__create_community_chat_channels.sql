CREATE TABLE community_chat_channels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id BIGINT NOT NULL REFERENCES communities(id) ON DELETE CASCADE,
    name VARCHAR(60) NOT NULL,
    name_key VARCHAR(180) NOT NULL,
    UNIQUE (community_id, name_key),
    UNIQUE (community_id, id)
);

ALTER TABLE community_chat_messages ADD COLUMN channel_id BIGINT;
ALTER TABLE community_chat_messages ADD CONSTRAINT fk_community_chat_message_channel
    FOREIGN KEY (community_id, channel_id)
    REFERENCES community_chat_channels(community_id, id) ON DELETE CASCADE;

CREATE INDEX idx_community_chat_channel_history ON community_chat_messages (community_id, channel_id, id);