CREATE TABLE task_organization (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind VARCHAR(12) NOT NULL CHECK (kind IN ('PROJECT', 'CATEGORY')),
    name VARCHAR(80) NOT NULL,
    name_key VARCHAR(240) NOT NULL,
    UNIQUE (user_id, kind, name_key)
);

ALTER TABLE tasks ADD COLUMN project_id BIGINT REFERENCES task_organization(id) ON DELETE SET NULL;
ALTER TABLE tasks ADD COLUMN category_id BIGINT REFERENCES task_organization(id) ON DELETE SET NULL;
CREATE INDEX idx_tasks_project ON tasks (project_id);
CREATE INDEX idx_tasks_category ON tasks (category_id);