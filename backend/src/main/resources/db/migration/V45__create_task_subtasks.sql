CREATE TABLE task_subtasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT REFERENCES tasks(id) ON DELETE CASCADE,
    community_task_id BIGINT REFERENCES community_tasks(id) ON DELETE CASCADE,
    description VARCHAR(150) NOT NULL,
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    CHECK ((task_id IS NULL) <> (community_task_id IS NULL))
);
CREATE INDEX idx_subtasks_personal ON task_subtasks (task_id, id);
CREATE INDEX idx_subtasks_community ON task_subtasks (community_task_id, id);